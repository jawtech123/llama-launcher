"""SSH key provisioning.

Installs a public key on a remote host so the launcher can stop storing that
host's password. The one-time install is authenticated with the password the
user just typed; everything afterwards uses the key.

Runs through the ordinary ``ssh``/``ssh-keygen`` binaries, so it inherits the
same auth handling (including the askpass helper) as the rest of the transport.
"""
import dataclasses
import logging
import os
import shlex
import subprocess
from pathlib import Path
from typing import Optional, Tuple

from .types import ServerConfig

logger = logging.getLogger(__name__)

#: Preferred key type: small, fast, and supported by every current OpenSSH.
_KEY_TYPE = "ed25519"

#: Key generated by the launcher when the user has none.
_LAUNCHER_KEY_NAME = "id_ed25519_llama_launcher"

#: Name used by earlier versions. Checked first: it may already be installed on
#: hosts set up back then, so generating a fresh key would needlessly ask for a
#: password on machines that already trust this one.
_LEGACY_LAUNCHER_KEY_NAME = "llama_launcher"

#: Existing keys to reuse before generating a launcher-specific one.
_COMMON_KEY_NAMES = (
    _LAUNCHER_KEY_NAME,
    _LEGACY_LAUNCHER_KEY_NAME,
    "id_ed25519",
    "id_rsa",
    "id_ecdsa",
)


def ssh_dir() -> Path:
    """The user's ~/.ssh, created with the permissions sshd insists on."""
    path = Path.home() / ".ssh"
    path.mkdir(mode=0o700, exist_ok=True)
    try:
        os.chmod(path, 0o700)
    except OSError:
        logger.warning("Could not set permissions 700 on %s", path)
    return path


def find_existing_key() -> Optional[Path]:
    """Return an existing usable private key, preferring the conventional ones."""
    base = Path.home() / ".ssh"
    for name in _COMMON_KEY_NAMES:
        candidate = base / name
        if candidate.is_file() and Path(f"{candidate}.pub").is_file():
            return candidate
    return None


def ensure_key_pair(key_path: Optional[str] = None) -> Tuple[Optional[Path], str]:
    """Return a usable key pair, generating one only if necessary.

    Returns ``(private_key_path, message)``; the path is None on failure.
    """
    if key_path:
        explicit = Path(key_path).expanduser()
        if explicit.is_file():
            # Append, never with_suffix: a key named "my.key" must look for
            # "my.key.pub", not "my.pub".
            if not Path(f"{explicit}.pub").is_file():
                return (None, f"No public key next to {explicit} (expected {explicit}.pub)")
            return (explicit, f"Using existing key {explicit}")

    existing = find_existing_key()
    if existing is not None:
        return (existing, f"Using existing key {existing}")

    target = ssh_dir() / _LAUNCHER_KEY_NAME
    try:
        result = subprocess.run(
            ["ssh-keygen", "-t", _KEY_TYPE, "-N", "", "-f", str(target),
             "-C", f"llama-launcher@{os.uname().nodename}"],
            capture_output=True, text=True, timeout=60,
        )
    except Exception as e:
        logger.debug("ssh-keygen failed", exc_info=True)
        return (None, f"Could not run ssh-keygen: {e}")
    if result.returncode != 0:
        return (None, f"ssh-keygen failed: {(result.stderr or '').strip()}")
    try:
        os.chmod(target, 0o600)
    except OSError:
        logger.warning("Could not set permissions 600 on %s", target)
    return (target, f"Generated a new key at {target}")


def read_public_key(private_key_path: Path) -> Optional[str]:
    """Read the public half of a key pair."""
    pub = Path(f"{private_key_path}.pub")
    try:
        return pub.read_text().strip()
    except OSError:
        logger.debug("Could not read public key %s", pub, exc_info=True)
        return None


def _install_command(public_key: str) -> str:
    """Shell command appending the key to authorized_keys, idempotently."""
    quoted = shlex.quote(public_key)
    return (
        "mkdir -p ~/.ssh && chmod 700 ~/.ssh && "
        "touch ~/.ssh/authorized_keys && chmod 600 ~/.ssh/authorized_keys && "
        f"(grep -qxF {quoted} ~/.ssh/authorized_keys || echo {quoted} >> ~/.ssh/authorized_keys)"
    )


def setup_key_auth(config: ServerConfig, password: str,
                   key_path: Optional[str] = None) -> Tuple[bool, str, str]:
    """Install a key on the host and confirm key-only login works.

    Args:
        config: The server to set up. Not modified.
        password: Used once, for the install itself. Never stored.
        key_path: Optional existing key to use instead of picking or generating.

    Returns ``(ok, message, key_path)``. On success the caller can switch the
    server to key auth and discard the password.
    """
    # Imported here: manager -> ssh is otherwise a lazy import, and this module
    # is only reached from the GUI.
    from .ssh import SSHServerConnection

    if not config.hostname.strip() or not config.username.strip():
        return (False, "Host and username are required.", "")
    if not password:
        return (False, "The account password is needed once to install the key.", "")

    private_key, message = ensure_key_pair(key_path)
    if private_key is None:
        return (False, message, "")

    public_key = read_public_key(private_key)
    if not public_key:
        return (False, f"Could not read the public key for {private_key}", "")

    # Connection reuse is disabled for both steps: the control socket is keyed
    # on host/port/user, not on credentials, so an existing master would let a
    # wrong password "succeed" and make the key check meaningless.

    # Step 1: install, authenticating with the password this one time.
    password_config = dataclasses.replace(
        config, auth_method="password", password=password, key_path="")
    installer = SSHServerConnection(password_config, allow_multiplexing=False)
    ok, probe_message = installer.test_connection()
    if not ok:
        return (False, f"Could not connect with that password: {probe_message}", "")
    if not installer.execute(_install_command(public_key)):
        detail = installer._last_stderr or "unknown error"
        return (False, f"Could not write authorized_keys: {detail}", "")

    # Step 2: prove key-only login works before telling the user to rely on it.
    key_config = dataclasses.replace(
        config, auth_method="key", password="", key_path=str(private_key))
    verifier = SSHServerConnection(key_config, allow_multiplexing=False)
    ok, verify_message = verifier.test_connection()
    if not ok:
        return (False,
                f"Key installed, but key-only login still failed: {verify_message}. "
                f"The password has been kept.",
                str(private_key))
    return (True, f"{message}. Key authentication is working; password no longer needed.",
            str(private_key))
